// Postcode district pages, transcribed from the supplied London workbook.
//
// A district is not the same thing as a neighbourhood: E1 covers ten named
// areas across three boroughs, E1W covers two in one. That list is the reason
// these pages exist and is the only thing on them that is genuinely per-page,
// so they are built around it rather than around invented local prose.
//
// Measured demand for postcode terms is low: every "plumber [district]" and
// "boiler repair [district]" term tested came back at 30 monthly searches or
// below, against 90-390 for the equivalent area name. These pages were built
// at the client's explicit direction after that was reported. They are kept
// deliberately lean and they link through to the area page, which is the page
// intended to rank.

// Whether the 122 district pages are offered to Google.
//
// Measured on the built output: each page is on average 40.9% its own writing
// against its closest sibling, lowest 33.0%. The service x location pages, for
// comparison, run 56-61%. The reason is arithmetic rather than effort — a
// district carries roughly 25 words of genuinely unique data (the code, its
// main area, an average of 3.4 neighbourhoods, its boroughs, its region) and a
// page cannot be made half-unique from 25 words without inventing local detail.
//
// Measured demand is also low: every postcode term tested returned 30 monthly
// searches or fewer, against 90-390 for the equivalent area name.
//
// Set to false to keep the pages live and useful for visitors who know their
// postcode, while removing them from the sitemap and marking them noindex, so
// Google is not asked to rank 122 near-identical URLs. Nothing else changes.
