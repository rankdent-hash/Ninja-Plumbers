{
  const problems: string[] = [];
  const seen = new Set<string>();
  for (const p of postcodes) {
    if (seen.has(p.slug)) problems.push(`duplicate slug: ${p.slug}`);
    seen.add(p.slug);
    if (!/^[a-z]{1,2}[0-9]{1,2}[a-z]?$/.test(p.slug)) problems.push(`odd slug: ${p.slug}`);
    if (p.boroughs.length === 0) problems.push(`${p.district}: no borough`);
  }
  if (problems.length) throw new Error('postcodes.ts invariants failed:\n  ' + problems.join('\n  '));
}

